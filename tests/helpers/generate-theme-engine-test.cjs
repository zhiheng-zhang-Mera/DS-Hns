'use strict'
/**
 * Generator for `tests/unit/theme-engine.test.js`.
 *
 * The test body is written from a data structure rather than by hand so the file
 * cannot accumulate the template-literal / indentation damage that hand-edited
 * scenario maps are prone to. Run from `tests/`:
 *
 *   node helpers/generate-theme-engine-test.cjs
 *
 * The generator is kept in the repository: it documents the scenario list and
 * makes adding a scenario a data edit rather than a code edit.
 */
const fs = require('node:fs')
const path = require('node:path')

const OUT = path.join(__dirname, '..', 'unit', 'theme-engine.test.js')

/** Each scenario is `{ kind, test, steps: { stepId: code } }`, plus assertion lines. */
const scenariosModule = require('./theme-engine-scenarios.cjs')
const SCENARIOS = scenariosModule.scenarios
const code = scenariosModule.code

const lines = []
lines.push("'use strict'")
lines.push("const test = require('node:test')")
lines.push("const assert = require('node:assert/strict')")
lines.push('')
lines.push('/**')
lines.push(' * Theme engine integration, executed in sandboxed child processes.')
lines.push(' *')
lines.push(' * The registry resolves its data directory from `DSH_ROOT` when the module is')
lines.push(' * first required, so an in-process test would install themes into the real')
lines.push(' * installation. Every scenario therefore runs against a throwaway project root')
lines.push(' * (see tests/helpers/theme-sandbox.cjs and tests/helpers/theme-suite.cjs).')
lines.push(' *')
lines.push(' * Generated by tests/helpers/generate-theme-engine-test.cjs.')
lines.push(' */')
lines.push("const { runOne, runEach } = require('../helpers/theme-suite.cjs')")
lines.push('')

for (const scenario of SCENARIOS) {
  lines.push(`test(${JSON.stringify(scenario.test)}, () => {`)
  if (scenario.kind === 'single') {
    lines.push('  const value = runOne({')
    for (const [id, body] of Object.entries(scenario.steps)) {
      lines.push(`    ${id}: ${JSON.stringify(code(body))},`)
    }
    lines.push('  })')
  } else {
    lines.push('  const value = runEach({')
    for (const [name, steps] of Object.entries(scenario.steps)) {
      lines.push(`    ${name}: {`)
      for (const [id, body] of Object.entries(steps)) {
        lines.push(`      ${id}: ${JSON.stringify(code(body))},`)
      }
      lines.push('    },')
    }
    lines.push('  })')
  }
  lines.push('')
  let first = true
  for (const assertion of scenario.asserts) {
    if (assertion === '') {
      lines.push('')
      first = true
      continue
    }
    // Multi-line assertion blocks are emitted verbatim; single lines are indented.
    if (assertion.startsWith('}') || assertion.startsWith('  ')) {
      lines.push(assertion)
    } else {
      lines.push(`  ${assertion}`)
    }
    first = false
  }
  lines.push('})')
  lines.push('')
}

fs.writeFileSync(OUT, `${lines.join('\n')}\n`, 'utf8')
console.log(`wrote ${OUT} (${lines.length} lines, ${SCENARIOS.length} tests)`)
