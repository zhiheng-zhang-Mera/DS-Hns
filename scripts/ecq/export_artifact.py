"""Export an explicit byte-for-byte research inventory from a fixed DS-Hns checkout."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
from concurrent.futures import ThreadPoolExecutor

PREFIXES = ('scripts/ecq', 'tests/ecq', 'docs/paper-material/revision-v37',
            'artifacts/paper-revision/ecq-v37')
EXCLUDED_PARTS = {'__pycache__', 'benchmark-fixtures', '.pytest_cache', '.venv', 'node_modules'}


def _sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def export(source_root, destination, source_commit):
    source_root, destination = Path(source_root).resolve(), Path(destination).resolve()
    if source_root == destination or source_root in destination.parents:
        raise ValueError('export destination must be outside source checkout')
    if destination.exists() and any(destination.iterdir()):
        raise ValueError('export destination must be new or empty; refuse overwrite')
    destination.mkdir(parents=True, exist_ok=True)
    inventory=[]
    for prefix in PREFIXES:
        folder=source_root/prefix
        if folder.exists():
            inventory.extend(path for path in folder.rglob('*') if path.is_file()
                             and not any(part in EXCLUDED_PARTS for part in path.relative_to(source_root).parts)
                             and path.suffix not in ('.pyc', '.pyo'))
    if (source_root/'LICENSE').is_file():inventory.append(source_root/'LICENSE')
    def copy_one(path):
        if path.is_symlink():raise ValueError('source symlink is not an immutable package file: '+str(path))
        relative=path.relative_to(source_root).as_posix();target=destination/relative
        target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(path,target)
        return relative,{'sha256':_sha(target),'sourcePath':relative,'origin':'DS-Hns snapshot'}
    with ThreadPoolExecutor(max_workers=16) as pool:
        sources=dict(pool.map(copy_one,sorted(inventory)))
    requirements=source_root/'docs/paper-material/revision-v37/requirements.lock'
    (destination/'requirements.lock').write_bytes(requirements.read_bytes() if requirements.exists() else b'')
    (destination/'README.md').write_text('''# ECQ v37 reproducible research artifact

This is a byte-preserving, explicitly inventoried snapshot of the DS-Hns research
implementation, tests, frozen protocol, source records, inputs, labels and raw
method outputs. MANIFEST.json identifies the immutable source commit and hashes.
Benchmark fixture bytes are generated by bench.cjs and are excluded; the recorded
scale settings and measurements are included. Python caches are excluded.

## Recompute without the original workspace

Python 3.12 or later is sufficient for hash/grid checks and analysis:

```
python scripts/ecq/reproduce.py --root .
```

The default verifies all inventoried bytes, frozen campaign grids and recomputes
metrics from archived independent labels and attempts. It compares the recomputed
main summaries with published summaries. It does not rerun experiments or install
dependencies. Outputs are written under reproduced/.

To rerun the frozen methods as well, install the locked Python dependencies into
an isolated environment, make Node.js 24 available, and run:

```
python -m pip install -r requirements.lock
python scripts/ecq/reproduce.py --root . --rerun
```

The frozen methods use local files; new source collection is unnecessary. Runtime
identity and observed cost measurements belong to the recorded environment. The
snapshot includes the original MIT license; cited source records retain their
upstream identity. Its oracle and analysis are independent of observer execution.
''',encoding='utf-8')
    (destination/'CITATION.cff').write_text('''cff-version: 1.2.0
message: "Please cite the associated ECQ v37 manuscript and immutable artifact commit."
title: "Evidence-Closed Qualification: v37 Research Artifact"
type: software
authors:
  - family-names: Zhang
    given-names: Zhiheng
    orcid: "https://orcid.org/0009-0005-9005-9931"
repository-code: "https://github.com/zhiheng-zhang-Mera/DS-Hns"
license: MIT
''',encoding='utf-8')
    for name in ('README.md','requirements.lock','CITATION.cff'):
        sources[name]={'sha256':_sha(destination/name),'sourcePath':None,'origin':'export metadata'}
    manifest={'schemaVersion':1,'sourceRepository':'zhiheng-zhang-Mera/DS-Hns',
              'sourceCommit':source_commit,'files':dict(sorted(sources.items())),
              'exclusions':sorted(EXCLUDED_PARTS),
              'reproduceCommand':'python scripts/ecq/reproduce.py --root .',
              'inventoryPolicy':'MANIFEST.json excludes itself; reproduced/ is generated verification output.'}
    (destination/'MANIFEST.json').write_text(json.dumps(manifest,indent=2,sort_keys=True)+'\n',encoding='utf-8')
    return manifest


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root',type=Path,required=True)
    parser.add_argument('--destination',type=Path,required=True)
    parser.add_argument('--source-commit',required=True)
    args=parser.parse_args();manifest=export(args.source_root,args.destination,args.source_commit)
    print(json.dumps({'sourceCommit':args.source_commit,'inventoriedFiles':len(manifest['files'])}))


if __name__=='__main__':main()
